def _get_builtin_metadata(dataset_name):
    if dataset_name == "coco":
        return _get_coco_instances_meta()
    elif dataset_name == "coco_fewshot":
        return _get_coco_fewshot_instances_meta()
    elif dataset_name == "voc_fewshot":
        return _get_voc_fewshot_instances_meta()
    elif dataset_name == 'miniin_fewshot':
        return _get_miniin_fewshot_instances_meta()
    elif dataset_name == 'cub_fewshot':
        return _get_cub_fewshot_instances_meta()
    elif dataset_name == 'dogs_fewshot':
        return _get_dogs_fewshot_instances_meta()
    elif dataset_name == 'cars_fewshot':
        return _get_cars_fewshot_instances_meta()
    raise KeyError("No built-in metadata for dataset {}".format(dataset_name))
